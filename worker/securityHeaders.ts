// Security headers for the site's pages and static assets. Used in two places:
// - worker/index.ts, for responses the Worker produces (API, guides, bridge, beta robots.txt);
// - vite.config.ts, which writes them to dist/_headers so Cloudflare applies them to static assets
//   served without running the Worker (see run_worker_first in wrangler.jsonc). Static asset
//   requests that skip the Worker do not count toward the Workers request quota.
// No imports and no Worker globals here: vite.config.ts loads this file under Node.

export const defaultStudioOrigin = 'https://artworkstudio.lannahirave.com';
export const defaultDemoOrigin = 'https://demoartwork.lannahirave.com';

export type SiteHeaderOptions = {
  /** Origin of Steam Artwork Studio, whose /bridge page SteamCanvas embeds for handoffs. */
  studioOrigin: string;
  /** Origin of the Studio's demo page, whose example GIFs ?demo= downloads. */
  demoOrigin: string;
  /** True on the beta deployment, so search engines skip it. */
  noindex: boolean;
};

// The profile preview iframe uses srcdoc, so it inherits this policy. Steam's own CSS, fonts,
// images and background videos must therefore be allowed, and base-uri must allow the
// <base href="https://steamcommunity.com/"> the server adds to the preview.
export function contentSecurityPolicy({ studioOrigin, demoOrigin }: SiteHeaderOptions): string {
  const steamAssets = 'https://*.steamstatic.com https://steamcommunity.com https://*.steamusercontent.com https://*.akamaihd.net';
  return [
    "default-src 'self'",
    "script-src 'self'",
    `style-src 'self' 'unsafe-inline' ${steamAssets} https://fonts.googleapis.com`,
    `img-src 'self' data: blob: ${steamAssets}`,
    `media-src 'self' data: blob: ${steamAssets}`,
    `font-src 'self' data: ${steamAssets} https://fonts.gstatic.com`,
    `connect-src 'self' data: blob: ${steamAssets} ${demoOrigin}`,
    `frame-src ${studioOrigin}`,
    "object-src 'none'",
    "base-uri 'self' https://steamcommunity.com",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** Headers for every page and asset except /bridge/. */
export function siteHeaders(options: SiteHeaderOptions): Record<string, string> {
  return {
    'X-Content-Type-Options': 'nosniff',
    'Content-Security-Policy': contentSecurityPolicy(options),
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    ...(options.noindex ? { 'X-Robots-Tag': 'noindex, nofollow' } : {}),
  };
}

function headersBlock(path: string, headers: Record<string, string>): string {
  return [path, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('
');
}

/**
 * Contents of dist/_headers. /bridge/ always runs the Worker, which sets its own headers, so it
 * is not listed. Vite's hashed /assets/ files never change, so browsers may keep them for a year
 * without asking again.
 */
export function staticHeadersFile(options: SiteHeaderOptions): string {
  const block = (path: string, headers: Record<string, string>) =>
    [path, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('\n');
  return [
    '# Generated by vite.config.ts from worker/securityHeaders.ts. Do not edit.',
    headersBlock('/*', siteHeaders(options)),
    headersBlock('/assets/*', { 'Cache-Control': 'public, max-age=31536000, immutable' }),
    '',
  ].join('\n');
}
